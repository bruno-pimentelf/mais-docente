export class CrosswordSlideFactory implements ICrosswordSlideFactory {
  constructor(private colors: SlideTypeColors) {}

  async create(
    title: string,
    image_url_1: string,
    image_url_2: string,
    logo_path: string,
    slideOrder: number
  ): Promise<Slide[]> {
    const slideWidth = SLIDE_WIDTH;
    const slideHeight = SLIDE_HEIGHT;

    const titleX = SLIDE_MARGIN;
    const titleY = SLIDE_ELEMENT_MIN_Y;
    const distanceFromMiddle = 20;
    const titleWidth = (slideWidth - SLIDE_MARGIN * 2) / 2 - distanceFromMiddle;

    const titleHeight = getTextHeight({
      text: `<span style="overflow-wrap: break-word; color: ${this.colors.titleColor}; font-weight: bold;">${processMarkdownFormatting(
        title
      )}</span>`,
      fontSize: 96,
      fontFamily: 'Quicksand',
      lineHeight: 1.0,
      width: titleWidth,
    });

    const titleElement: SlideText = {
      id: v4(),
      type: SlideElementBaseTypes.TEXT,
      subtype: SlideTextElementsVariants.PARAGRAPH,
      text: `<span style="overflow-wrap: break-word; color: ${this.colors.titleColor}; font-weight: bold;">${processMarkdownFormatting(
        title
      )}</span>`,
      x: titleX,
      y: titleY,
      width: titleWidth,
      height: titleHeight,
      options: { isVisible: true, label: 'Title' },
      fontSize: 96,
      fontFamily: 'Quicksand',
      textAlign: TextAlignment.Left,
      lineHeight: 1.0,
    };

    const logoTitleElement = getLogoImageElement(logo_path);

    // Image element that touches right and top margins
    const decorativeImageWidth = 1053;
    const decorativeImageHeight = 948;
    const decorativeImageX = slideWidth - SLIDE_MARGIN - decorativeImageWidth; // Touches right margin
    const decorativeImageY = SLIDE_MARGIN; // Touches top margin

    // Color the SVG with the theme's line color and convert to data URL
    const coloredStrokeSvg = getColoredStrokeSvg(
      crosswordSvg,
      this.colors.lineColor
    );
    const coloredSvg = getColoredFillSvg(
      coloredStrokeSvg,
      this.colors.paragraphColor
    );
    const svgDataUrl = `data:image/svg+xml;charset=utf-8,${encodeURIComponent(coloredSvg)}`;

    const decorativeImageElement: SlideImage = {
      id: v4(),
      type: SlideElementBaseTypes.IMAGE,
      subtype: SlideImageElementsVariants.IMAGE,
      src: svgDataUrl,
      x: decorativeImageX,
      y: decorativeImageY,
      width: decorativeImageWidth,
      height: decorativeImageHeight,
      options: { isVisible: true, label: 'Crossword Image' },
    };

    const titleSlide: Slide = {
      id: v4(),
      order: slideOrder,
      variant: SlideVariants.CUSTOM,
      layout: SlideLayoutVariants.FULL_CONTENT,
      slideType: SlideThemeType.CUSTOM,
      themeSettings: {
        baseWidth: slideWidth,
        baseHeight: slideHeight,
        width: slideWidth,
        height: slideHeight,
        backgroundColor: this.colors.backgroundColor,
      },
      elements: [titleElement, decorativeImageElement, logoTitleElement],
    };

    // Load image dimensions to calculate proper sizing
    const [image1Dimensions, image2Dimensions] = await Promise.all([
      getImageDimensions(image_url_1),
      getImageDimensions(image_url_2),
    ]);

    // Calculate image dimensions for full height
    // Images should occupy the whole slide height including margins
    const imageHeight = slideHeight; // Full slide height (1080px)

    // Calculate width maintaining aspect ratio
    const image1Width = Math.round(
      (image1Dimensions.width / image1Dimensions.height) * imageHeight
    );
    const image2Width = Math.round(
      (image2Dimensions.width / image2Dimensions.height) * imageHeight
    );

    // Center images horizontally
    const image1X = Math.round((slideWidth - image1Width) / 2);
    const image2X = Math.round((slideWidth - image2Width) / 2);

    // Create first slide with first image
    const image1Element: SlideImage = {
      id: v4(),
      type: SlideElementBaseTypes.IMAGE,
      subtype: SlideImageElementsVariants.IMAGE,
      src: image_url_1,
      x: image1X,
      y: 0,
      width: image1Width,
      height: imageHeight,
      options: { isVisible: true, label: 'Crossword Image 1' },
    };

    const logoImageElement1 = getLogoImageElement(logo_path);

    const slide1: Slide = {
      id: v4(),
      order: slideOrder + 1,
      variant: SlideVariants.CUSTOM,
      layout: SlideLayoutVariants.FULL_CONTENT,
      slideType: SlideThemeType.CUSTOM,
      themeSettings: {
        baseWidth: slideWidth,
        baseHeight: slideHeight,
        width: slideWidth,
        height: slideHeight,
        backgroundColor: '#FFFFFF',
      },
      elements: [image1Element, logoImageElement1],
    };

    // Create second slide with second image
    const image2Element: SlideImage = {
      id: v4(),
      type: SlideElementBaseTypes.IMAGE,
      subtype: SlideImageElementsVariants.IMAGE,
      src: image_url_2,
      x: image2X,
      y: 0,
      width: image2Width,
      height: imageHeight,
      options: { isVisible: true, label: 'Crossword Image 2' },
    };

    const logoImageElement2 = getLogoImageElement(logo_path);

    const slide2: Slide = {
      id: v4(),
      order: slideOrder + 2,
      variant: SlideVariants.CUSTOM,
      layout: SlideLayoutVariants.FULL_CONTENT,
      slideType: SlideThemeType.CUSTOM,
      themeSettings: {
        baseWidth: slideWidth,
        baseHeight: slideHeight,
        width: slideWidth,
        height: slideHeight,
        backgroundColor: '#FFFFFF',
      },
      elements: [image2Element, logoImageElement2],
    };

    return [titleSlide, slide1, slide2];
  }
}
